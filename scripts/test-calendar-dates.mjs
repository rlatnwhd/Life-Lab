import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const compile=file=>ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const url=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const modelUrl=url(compile(new URL('../src/model.ts',import.meta.url)));
const dates=await import(url(compile(new URL('../src/calendarDates.ts',import.meta.url)).replace("'./model'",JSON.stringify(modelUrl))));
assert.equal(dates.weekStart('2026-04-01'),'2026-03-30');
assert.equal(dates.weekStart('2027-01-01'),'2026-12-28');
assert.equal(dates.monthDate(2026,1,31),'2026-02-28');
assert.equal(dates.monthDate(2028,1,31),'2028-02-29');
assert.equal(dates.shiftMonth('2028-03-31',-1),'2028-02-29');
assert.equal(dates.shiftMonth('2026-12-19',1),'2027-01-19');
const feb=dates.monthCells(2026,1);
assert.equal(feb.length,42);assert.equal(feb[0],'2026-01-26');assert.equal(feb[41],'2026-03-08');
assert.equal(dates.calendarDateAllowed('1899-12-31'),false);
assert.equal(dates.calendarDateAllowed('2101-01-01'),false);
assert.equal(dates.calendarDateAllowed('2028-02-29'),true);
console.log('Passed: Monday-based weeks, month/year boundaries, leap day, clamped month navigation and supported year limits.');
