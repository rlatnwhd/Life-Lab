import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const compile=file=>ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const url=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const modelUrl=url(compile(new URL('../src/model.ts',import.meta.url)));
const {dashboardSummary}=await import(url(compile(new URL('../src/dashboard.ts',import.meta.url)).replace("'./model'",JSON.stringify(modelUrl))));
const today='2026-11-18';
const e={id:'a',title:'Focus',a:'Music',b:'Quiet',hypothesis:'',days:7,start:'2026-11-16',metric:'Focus',unit:'points',max:10,category:'Study',entries:[{date:'2026-11-17',score:7,note:''}]};
const saved={...e,id:'b',entries:[{date:today,score:8,note:''}]};
const future={...e,id:'future',start:'2026-11-25',entries:[]};
const completed={...e,id:'done',start:'2026-11-01',entries:[]};
const summary=dashboardSummary([e,saved,future,completed],today);
assert.equal(summary.active.length,2);
assert.deepEqual(summary.pending.map(e=>e.id),['a']);
assert.equal(summary.todayCount,1);
assert.equal(summary.totalCount,2);
assert.equal(summary.finishedCount,1);
assert.equal(summary.days[0].date,'2026-11-16');
assert.equal(summary.days[6].date,'2026-11-22');
assert.equal(summary.weekCount,2);
assert.equal(dashboardSummary([saved],today).pending.length,0);
assert.equal(dashboardSummary([],today).active.length,0);
assert.equal(dashboardSummary([],today).todayCount,0);
assert.equal(dashboardSummary([],today).totalCount,0);
console.log('Passed: personalized dashboard counts, pending experiment, completed and future experiments, week boundaries and empty account.');
