import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const compile=path=>ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const url=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const modelUrl=url(compile(new URL('../src/model.ts',import.meta.url)));
const model=await import(modelUrl);
const cloud=await import(url(compile(new URL('../src/cloud-model.ts',import.meta.url)).replace("'./model'",JSON.stringify(modelUrl))));
const e={...model.examples()[0],id:'test-cloud',demo:false};
for (const max of [1,1.5,5.1,10,100]) cloud.validateNewMeasurement({...e,max});
for (const max of [0,-1,101,10000,NaN,Infinity,1.55]) assert.throws(()=>cloud.validateNewMeasurement({...e,max}));
cloud.validateNewMeasurement({...e,unit:'분',max:100});
assert.throws(()=>cloud.validateNewMeasurement({...e,unit:'분',max:101}));
// Historical experiments remain readable even when their old range exceeds the new creation limit.
assert.equal(cloud.fromCloud(e.id,cloud.toCloud({...e,max:10000})).max,10000);
const data=cloud.toCloud(e);
assert.equal(data.entries[e.entries[0].date].score,e.entries[0].score);
assert.equal('id' in data,false);
assert.equal('demo' in data,false);
assert.deepEqual(cloud.fromCloud(e.id,data).entries,e.entries);
assert.throws(()=>cloud.validateEntry(e,{date:model.dayKey(),score:11,note:''}));
assert.throws(()=>cloud.validateEntry(e,{date:model.offset(e.start,-1),score:7,note:''}));
assert.throws(()=>cloud.validateEntry(e,{date:model.offset(model.dayKey(),1),score:7,note:''}));
assert.throws(()=>cloud.validateEntry(e,{date:model.dayKey(),score:NaN,note:''}));
assert.throws(()=>cloud.validateEntry(e,{date:model.dayKey(),score:7,note:'x'.repeat(501)}));
assert.throws(()=>cloud.toCloud({...e,id:'users/other'}));
assert.throws(()=>cloud.toCloud({...e,title:' '}));
assert.throws(()=>cloud.toCloud({...e,entries:[e.entries[0],e.entries[0]]}));
assert.throws(()=>cloud.fromCloud(e.id,{...data,entries:{bad:e.entries[0]}}));
assert.throws(()=>cloud.fromCloud(e.id,{...data,entries:[]}));
assert.match(cloud.firebaseMessage({code:'permission-denied'}),/firestore.rules/);
assert.match(cloud.firebaseMessage({code:'auth/unauthorized-domain'}),/localhost/);
console.log('Passed: cloud serialization, date/score validation, duplicate records, safe document IDs, readable Auth/Firestore errors.');
